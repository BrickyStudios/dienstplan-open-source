--
-- Befund 1 der Sicherheitspruefung vom 14.09.2026
-- (docs/sicherheit/SICHERHEITSPRUEFUNG-20260914.md).
--
-- In 20260529_features_oncall_agencies_analytics.sql, Zeile 71-74, stand:
--
--     create policy "external_agency_requests_public_token"
--       on external_agency_requests for select
--       using (true);
--
-- `using (true)` ohne TO-Klausel gilt fuer `public`, und das schliesst `anon`
-- ein. Der anon-Key steht im JavaScript jeder Seite (NEXT_PUBLIC_* wird beim
-- Build in das Client-Bundle gebacken, das Dockerfile sagt es selbst). Jeder
-- konnte damit
--
--     GET /rest/v1/external_agency_requests?select=*
--
-- abfragen und bekam jede Zeile aus jeder Einrichtung:
--
--   * facility_name ueber alle Zeilen  = die vollstaendige Kundenliste
--   * agency_name, agency_email        = die Lieferantenbeziehungen
--   * responder_name, responder_phone  = personenbezogene Daten Dritter
--   * response_token                   = der Magic-Link-Token JEDER offenen
--                                        Personalanfrage
--
-- Mit dem Token laesst sich POST /api/external/respond {token, answer} schicken.
-- Die Route prueft nur, ob der Token existiert — mehr kann sie nicht, sie ist
-- bewusst ohne Anmeldung. Bei "accepted" wird die Krankmeldung auf `covered`
-- gesetzt: die Leitung sieht eine besetzte Schicht, und es kommt niemand. In
-- einem Krankenhaus ist das kein Datenschutz-, sondern ein
-- Patientensicherheitsproblem. Bei "declined" ist die Anfrage tot, bevor der
-- Dienstleister die Mail ueberhaupt oeffnet.
--
-- Die Anwendung braucht die Policy NICHT: /api/external/respond liest ueber
-- lib/admin-client.ts mit dem service_role-Schluessel und umgeht RLS ohnehin.
-- Der Magic-Link funktioniert danach unveraendert. Kein Deploy noetig.
--
-- Derselbe Fehler war fuer invite_codes schon einmal da, siehe
-- 20260722_invite_codes_drop_public_select.sql. Seit dem 15.09.2026 sucht
-- __tests__/rls-oeffentlich-lesbar.test.ts danach.
--
-- NACH dem Ausfuehren: nachsehen, ob jemand durchgegangen ist. Erst zumachen,
-- dann pruefen — (1) hat die Tabelle in Produktion ueberhaupt Zeilen, (2)
-- zeigen die Supabase-Logs Zugriffe der Rolle `anon` darauf? Falls ja:
-- Art. 33 DSGVO, 72 Stunden. An diese Logs kommt nur der Tech-Founder.

drop policy if exists "external_agency_requests_public_token" on external_agency_requests;
